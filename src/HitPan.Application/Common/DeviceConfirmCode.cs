namespace HitPan.Application.Common;

/// <summary>
/// 기기 등록 **확인번호** — 대표가 눈으로 대조하는 4자리 숫자 (20260816작2 · 사장님 결재).
///
/// <para>
/// 사장님 설계: 대표 화면에 *"{기기이름} (인증번호 4726) 가 등록을 요청합니다"* 가 뜨고,
/// <b>신청한 기기 화면에도 같은 4726 이 뜬다.</b> 대표는 두 번호가 같은지 보고 [예] 를 누른다.
/// </para>
///
/// <para>
/// 🔴 <b>왜 필요한가</b> — 기기 이름만으로는 구분이 안 된다.
/// 브라우저가 알려주는 이름은 "Windows · Chrome" 수준이라 사무실에 같은 PC 가 여러 대면
/// 대표는 <b>어느 것을 승인하는지 모른다.</b> 모르면 아무거나 누르게 되고, 그 순간 승인제가 무의미해진다.
/// </para>
///
/// <para>
/// 🔴 <b>왜 저장하지 않는가</b> — 번호를 <c>device_id</c> 에서 <b>계산</b>한다.
/// 같은 기기면 항상 같은 번호가 나오므로 DB 컬럼도, 만료 관리도, 재발급도 필요 없다.
/// 저장하는 순간 "언제 지우나 · 다시 뜨면 같은 번호인가" 가 전부 새 결함 자리가 된다.
/// </para>
///
/// <para>
/// ⚠️ <b>이것은 비밀번호가 아니다.</b> 열쇠 역할을 하지 않는다 —
/// 승인 권한은 대표계정(tenant_admin)에게만 있고, 이 번호를 안다고 승인할 수 있는 게 아니다.
/// 이 번호가 하는 일은 오직 <b>"화면의 이 요청이 내 앞의 저 기기가 맞나"</b> 를 눈으로 잇는 것뿐이다.
/// 그래서 짧아도 되고, 화면에 그대로 보여도 된다.
/// </para>
///
/// <para>
/// ⚠️ 다만 <b>알림에는 싣지 않는다</b> (1차 사장님 결재 — <i>"옆에서 보면 샌다"</i>).
/// 화면에서만 본다.
/// </para>
///
/// <para>
/// 🔴 <b>이 계산은 여기 한 곳에만 둔다.</b> 신청 기기 화면과 대표 승인 화면이 서로 다른 계산을 쓰면
/// 번호가 안 맞아 <b>대조 자체가 거짓</b>이 된다 — 대표는 다르다고 보고 거절하거나,
/// 더 나쁘게는 번호를 무시하는 습관이 든다.
/// </para>
/// </summary>
public static class DeviceConfirmCode
{
    /// <summary>
    /// 기기 식별자에서 4자리 확인번호를 만든다. 같은 입력이면 언제나 같은 출력이다.
    /// </summary>
    /// <param name="deviceId">기기 UUID. 비어 있으면 <c>null</c> 을 돌려준다(보여줄 번호가 없다).</param>
    public static string? From(string? deviceId)
    {
        if (string.IsNullOrWhiteSpace(deviceId)) return null;

        // FNV-1a 32bit — 외부 의존 없이 한 번에 계산된다.
        //   ⚠️ 암호용이 아니다. 위 설명대로 이 번호는 열쇠가 아니라 **눈으로 잇는 표식**이다.
        unchecked
        {
            uint h = 2166136261u;
            foreach (var c in deviceId)
            {
                h ^= c;
                h *= 16777619u;
            }

            // 0000~9999. 앞자리 0 도 그대로 보여준다("0042" 가 "42" 로 보이면 대조가 흔들린다).
            return (h % 10000u).ToString("D4");
        }
    }
}
