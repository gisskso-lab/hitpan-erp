-- DB-129: 세션 생존 확인을 축 B 스위치에서 떼어낸다 (tenant_settings.enforce_session_validity)
-- =============================================================
-- 근거: PM 전결 2026-09-27 — docs/운영기록/20260927_PM전결_VB3_통제분리_결재.md §2 「안 다 — 통제를 두 스위치로 분리」
--       병렬이슈 V-B3:  docs/검증/병렬이슈/20260927_병렬이슈_축B봉합_보안반증.md §3
--       작업리뷰서 P2:  docs/검증/erp/20260927_작업리뷰서_축B봉합.md
--       앞 차수 마이그: DB-128(축 B 기본 OFF) — 이 파일은 그것을 되돌리지 않는다. 다른 스위치다.
--
-- ─────────────────────────────────────────────────────────────
-- 무엇이 문제였나 — 스위치 하나가 성질이 다른 두 통제를 함께 끄고 있었다
-- ─────────────────────────────────────────────────────────────
--
--   SessionValidityMiddleware:84 가 축 B 킬스위치(`enforce_single_pc_login`)가 꺼져 있으면
--   **세션 생존 확인을 통째로 건너뛰었다.** 그리고 우리는 축 B 를 기본 OFF 로 출하한다(DB-128).
--   ⇒ 출하 상태에서 **로그아웃·밀어내기가 액세스 토큰 수명(8시간) 내내 효력이 없다.**
--
--       ㉮ 세션 생존 확인   = 로그아웃·밀어내기를 즉시(≤10초) 반영 → **정합성**. 모든 고객이 원한다
--       ㉯ PC 동시로그인 차단 = 같은 계정 2번째 PC 를 409 로 막는다 → **정책**. 과금을 켠 고객만
--
--   정합성과 정책을 한 스위치에 묶을 이유가 없었다. 이 파일이 ㉮ 의 스위치를 따로 만든다.
--
--       enforce_session_validity   (이 파일 · DB-129)  DEFAULT 1 — ㉮. 끄면 로그아웃 반영이 늦는다. **비상용**
--       enforce_single_pc_login    (기존   · DB-128)  DEFAULT 0 — ㉯. 축 B 정책 그 자체
--
--   ⇒ 출하 상태: **로그아웃은 즉시 듣고, PC 차단은 안 걸린다.**
--     9/25 결재(모바일 FREE · PC 와 동시 가능)와 어긋나지 않는다.
--
-- ─────────────────────────────────────────────────────────────
-- 🔴 DB-128 의 교훈을 여기에 어떻게 적용했나 — 기존 행까지 닫는다
-- ─────────────────────────────────────────────────────────────
--
--   DB-128 머리말이 남긴 사고: `ADD COLUMN IF NOT EXISTS` 로 만들어 둔 컬럼은
--   나중에 그 줄의 `DEFAULT` 를 고쳐도 **이미 적용한 DB 가 한 줄도 안 바뀐다**(문장이 통째로 건너뛰어진다).
--   그래서 이 파일도 새 행·기존 행 **양쪽**을 각각 닫는다.
--
--       ① ADD COLUMN IF NOT EXISTS … NOT NULL DEFAULT 1
--          컬럼이 없던 DB: MariaDB 가 **기존 행 전부에 DEFAULT 값 1 을 채워 넣는다.**
--          🟢 실측(2026-09-27 · hitpan_trgtest · MariaDB 11.4.10): 행 2건이 있는 표에
--             이 문장 하나만 돌려 두 행 모두 1 이 됐다 ⇒ **정상 경로에는 UPDATE 가 필요 없다.**
--          ⚠️ 그래서 아래 ③ 을 전면 UPDATE 로 쓰지 않았다 — 그 이유가 ③ 에 있다.
--
--       ② MODIFY COLUMN … NOT NULL DEFAULT 1
--          컬럼이 **이미 있던** DB(손으로 만든 것·부분 적용)에서 ① 이 건너뛰어졌을 때를 닫는다.
--          MODIFY 는 **기본값만** 바꾼다 — 고객이 저장해 둔 값은 손대지 않는다.
--          ⇒ 「출하 DDL·DB-129 양쪽에서 기본값이 1」(게이트 G-B15)이 여기서 성립한다.
--
--       ③ UPDATE 는 **일부러 넣지 않는다** — 넣으면 비상 스위치를 되살린다
--          🔴 이 컬럼은 **0 이 정당한 고객 상태**다(전결 §2 — "0=비상 끔").
--            DB-128 은 값 1 이 애초에 의도된 적 없는 상태였으므로 전면 UPDATE 가 맞았다.
--            여기서 `UPDATE … SET enforce_session_validity = 1` 을 쓰면,
--            비상으로 끈 고객사가 **다음 업데이트에서 소리 없이 다시 켜진다.**
--            마이그는 멱등이어야 하고(재적용 가능), 재적용이 고객 설정을 뒤집으면 안 된다.
--          ⇒ ① 이 기존 행을 채우고, ② 가 기본값을 고정하고, **값 뒤집기는 하지 않는다.**
--          ⚠️ 남은 구멍(숨기지 않는다): 컬럼이 이미 있고 값이 0 으로 저장돼 있던 DB 는
--            이 마이그 뒤에도 0 이다. 그 상태는 **고객이 껐거나(정당) 손으로 만든 표(비정상)** 둘 중 하나인데
--            SQL 로는 두 경우를 못 가른다. 정당한 쪽을 지키는 편을 골랐다.
--
-- ─────────────────────────────────────────────────────────────
-- 🚫 건드리지 않는 것
-- ─────────────────────────────────────────────────────────────
--
--   · `enforce_single_pc_login`(축 B) — DB-128 이 0 으로 내려둔 그대로다. 이번 차수는 **스위치 분리**다
--   · `enforce_tenant_session_limit`(축 A) — 다른 축. 손대지 않는다
--   · `user_sessions` · `refresh_tokens` — 표 모양 변경 없음
--   · 컬럼 삭제·이름변경 없음 (헌법 #1 추가만 · #37)
--   · 새 표 없음 ⇒ ENGINE 지정 대상도 없다 (#17 해당 없음)
--
-- 대상 DB: hitpan_erp (고객 PC 로컬 ERP DB)
--          신규 설치 단일 진실원 installer/hitpan_db_clean.sql 에 함께 편입한다(헌법 #36).
--          🔴 clean DDL 의 `schema_migrations` 시드에 ('DB-129','clean-ddl',1) 도 같이 넣었다.
--             빠뜨리면 신규설치 고객이 이 마이그를 영원히 건너뛴다(DB-89·DB-126 선례).
-- 헌법: #1 추가만 / #13 DESCRIBE 선행(2026-09-27 실측 — 아래) / #36 clean DDL 편입 / #37
