-- ─────────────────────────────────────────────────────────────
-- 🔴 DB-128 의 교훈을 여기에 어떻게 적용했나 — 기존 행까지 닫는다
-- ─────────────────────────────────────────────────────────────
--
--   DB-128 머리말이 남긴 사고: `ADD COLUMN IF NOT EXISTS` 로 만들어 둔 컬럼은
--   나중에 그 줄의 `DEFAULT` 를 고쳐도 **이미 적용한 DB 가 한 줄도 안 바뀐다**(문장이 통째로 건너뛰어진다).
--   그래서 이 파일도 새 행·기존 행 **양쪽**을 각각 닫는다.
--
--       ① ADD COLUMN IF NOT EXISTS … NOT NULL DEFAULT 1
--          컬럼이 없던 DB: MariaDB 가 **기존 행 전부에 DEFAULT 값 1 을 채워 넣는다.**
--          🟢 실측(2026-09-27 · hitpan_trgtest · MariaDB 11.4.10): 행 2건이 있는 표에
--             이 문장 하나만 돌려 두 행 모두 1 이 됐다 ⇒ **정상 경로에는 UPDATE 가 필요 없다.**
--          ⚠️ 그래서 아래 ③ 을 전면 UPDATE 로 쓰지 않았다 — 그 이유가 ③ 에 있다.
--
--       ② MODIFY COLUMN … NOT NULL DEFAULT 1
--          컬럼이 **이미 있던** DB(손으로 만든 것·부분 적용)에서 ① 이 건너뛰어졌을 때를 닫는다.
--          MODIFY 는 **기본값만** 바꾼다 — 고객이 저장해 둔 값은 손대지 않는다.
--          ⇒ 「출하 DDL·DB-129 양쪽에서 기본값이 1」(게이트 G-B15)이 여기서 성립한다.
--
--       ③ UPDATE 는 **일부러 넣지 않는다** — 넣으면 장차 비상 스위치를 되살린다
--          🔴 [6차 정정 · [4] V-6] 여기 적혀 있던 근거가 **현재 시제로 틀렸다.**
--            ⬛ [낡은 줄 · 4차] *"이 컬럼은 **0 이 정당한 고객 상태**다(전결 §2 — 0=비상 끔)."*
--            오늘 그 상태는 **존재할 수 없다.** 근거 셋 — ⓐ 이 컬럼이 처음 나가는 차수다(어느 출하본에도
--            없었다) ⓑ **값을 0 으로 쓰는 경로가 코드에 0건이다**(끄는 길은 DB 한 줄 수술뿐이고,
--            설정 화면은 별건이다 — 전결 §5 가 스스로 적었다) ⓒ 출하 DDL·①·② 가 전부 1 이다.
--          🔴 [정확한 서술 · 미래형] 이 컬럼은 **0 이 정당해질 수 있는** 상태다.
--            쓰기 경로(설정 화면·비상 끄기 API)가 **생기는 순간**부터 0 은 *"고객이 비상으로 껐다"* 는
--            정당한 값이 되고, 그때 `UPDATE … SET enforce_session_validity = 1` 이 남아 있으면
--            **비상으로 끈 고객사가 다음 업데이트에서 소리 없이 다시 켜진다.**
--            마이그는 멱등이어야 하고(재적용 가능), 재적용이 고객 설정을 뒤집으면 안 된다.
--            ⇒ 그 경로가 생길 때 **넣지 않은 이 판단이 유효해진다.** 미리 지켜 둔다.
--          ⇒ ① 이 기존 행을 채우고, ② 가 기본값을 고정하고, **값 뒤집기는 하지 않는다.**
--          ⚠️ 남은 구멍(숨기지 않는다): 컬럼이 이미 있고 값이 0 으로 저장돼 있던 DB 는
--            이 마이그 뒤에도 0 이다. **오늘 그 경우에 물리는 것은 개발·시험 DB 와 손으로 만든 표뿐**이고
--            (고객 PC 에서 0 이 만들어질 길이 없다 — 위 ⓑ), 그 DB 는 생존확인이 **조용히 꺼진 채** 돈다.
--            쓰기 경로가 생기면 여기에 *"고객이 껐다(정당)"* 가 합류하는데 SQL 로는 두 경우를 못 가른다.
--            ⇒ 그때 함께 결재할 것: **비상으로 끈 사실을 어디에 남기나**(끈 시각·주체). 지금은 필요 없다.
