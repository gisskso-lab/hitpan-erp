--   ⚠️ hitpan_e2e 는 읽기만 했다(#39). 실제 적용 실측은 hitpan_trgtest 에서 했다.
--
-- 멱등: ① IF NOT EXISTS · ② 같은 정의로 다시 돌려도 안전 · ③ 없음. 재적용해도 결과가 같다.
-- =============================================================

-- ① 컬럼 신설 — 없던 DB 에서는 이 한 문장이 기존 행까지 1 로 채운다
ALTER TABLE tenant_settings
    ADD COLUMN IF NOT EXISTS enforce_session_validity TINYINT(1) NOT NULL DEFAULT 1
        COMMENT '세션 생존 확인(로그아웃·밀어내기 즉시 반영). 0=비상 끔. 축B(enforce_single_pc_login)와 별개 스위치 (DB-129)';

-- ② 컬럼이 이미 있던 DB 에서 ① 이 건너뛰어졌을 때 기본값을 1 로 고정한다
--   🔴 이 문장이 없으면 ①을 건너뛴 DB 는 기본값이 무엇이든 그대로다 — G-B15 음성 대조군.
--   값은 건드리지 않는다(위 ③ 참조 — 비상으로 끈 고객을 되살리지 않는다).
ALTER TABLE tenant_settings
    MODIFY COLUMN enforce_session_validity TINYINT(1) NOT NULL DEFAULT 1
        COMMENT '세션 생존 확인(로그아웃·밀어내기 즉시 반영). 0=비상 끔. 축B(enforce_single_pc_login)와 별개 스위치 (DB-129)';
