-- ─────────────────────────────────────────────────────────────
-- 무엇이 문제였나 — 스위치 하나가 성질이 다른 두 통제를 함께 끄고 있었다
-- ─────────────────────────────────────────────────────────────
--
--   SessionValidityMiddleware 의 생존확인 스위치 판독(`IsSessionValidityEnforcedAsync` 호출 —
--   `sid` 판독 **뒤**, 세션 생존 조회 **앞**. ⬛ 3차까지 이름은 `IsSinglePcLoginEnabledAsync` 였다)이
--   축 B 킬스위치(`enforce_single_pc_login`)가 꺼져 있으면
--   **세션 생존 확인을 통째로 건너뛰었다.** 그리고 우리는 축 B 를 기본 OFF 로 출하한다(DB-128).
--   🔴 [6차 정정 · [4] V-9] 여기 적혀 있던 `SessionValidityMiddleware:84` 는 **어긋난 줄번호**였다
--     (4차가 자기 주석 14줄을 얹는 순간 이미 밀렸다 — 실제 판독은 `:103`, 6차 주석 뒤엔 또 다르다).
--     ⇒ 줄번호를 쓰지 않는다. **메서드·조건 이름**으로 가리킨다(같은 사고 3회 재발).
--   ⇒ 출하 상태에서 **로그아웃·밀어내기가 액세스 토큰 수명(8시간) 내내 효력이 없다.**
--
--       ㉮ 세션 생존 확인   = 로그아웃·밀어내기를 즉시(≤10초) 반영 → **정합성**. 모든 고객이 원한다
--       ㉯ PC 동시로그인 차단 = 같은 계정 2번째 PC 를 409 로 막는다 → **정책**. 과금을 켠 고객만
--
--   정합성과 정책을 한 스위치에 묶을 이유가 없었다. 이 파일이 ㉮ 의 스위치를 따로 만든다.
--
--       enforce_session_validity   (이 파일 · DB-129)  DEFAULT 1 — ㉮. 끄면 로그아웃 반영이 늦는다. **비상용**
--       enforce_single_pc_login    (기존   · DB-128)  DEFAULT 0 — ㉯. 축 B 정책 그 자체
--
--   ⇒ 출하 상태: **로그아웃은 즉시 듣고, PC 차단은 안 걸린다.**
--     9/25 결재(모바일 FREE · PC 와 동시 가능)와 어긋나지 않는다.
--   ⚠️ [6차 단서 · [4] V-5 · 별건] **예외가 있다** — `TenantMiddleware` 화이트리스트 주소
--     (`/api/landing`·`/api/install`·`/api/internal`·`/api/setup`·`/api/devices/mainpc-proof`·
--     `/api/backoffice/auth`)와 **문서 다운로드**(`/api/documents/**/excel|pdf`)는 `TenantId` 를
--     세우지 않고 지나가므로, 생존확인이 스위치를 못 읽어 **통째로 건너뛴다**(fail-open).
--     그 주소들에서는 로그아웃·밀어내기 뒤에도 액세스 토큰 수명 동안 열려 있다.
--     ⇒ *"로그아웃은 즉시 듣는다"* 는 **그 주소들을 제외한 보호 API** 에 대한 말이다.
--     🚫 6차 범위 밖이다(코드 미수정 · 별건 결재 대상).
