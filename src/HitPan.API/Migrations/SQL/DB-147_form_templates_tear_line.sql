-- =============================================================
-- DB-147: 양식 인쇄 옵션 — 「가운데 자르는 선」 켬/끔
-- =============================================================
-- 근거: 20261021작 §10-2 ⓑ (사장님 재결재 2026-10-21)
--       *"절취선 — 켜고 끄는 것을 고객이 설정한다"*
--       작업지시서 §10-4 S-2
--
-- 🔴 왜 필요한가
--   세금계산서 한 벌이 A4 반 장에 들어가도록 줄이고 나니(§10-4 S-1),
--   「한 장에 두 벌 + 가운데 자르는 선」이 비로소 가능해졌다.
--   그런데 **그 종이를 원하지 않는 고객이 있다** — 보관용을 각각 한 장씩
--   온전히 쓰고 싶은 곳이다. 그래서 고객이 고르게 한다.
--
--   켬 → 한 장에 두 벌 + 가운데 자르는 선 (품목이 많으면 마지막 칸에 「외 N건」)
--   끔 → 벌마다 한 쪽씩 두 쪽 + 품목 전부
--
-- 🔴 기본값을 0(끔)으로 두는 이유 — **지금 동작과 같게** 맞춘 것이다
--   ① 이 칸이 생기기 직전(c44c82fa) 실측: 한 벌이 419.7pt 라 **어떤 여백에서도**
--      두 벌이 한 장에 안 들어갔다 ⇒ 모든 세금계산서가 **두 쪽 · 자르는 선 없음 ·
--      품목 전부** 로 나왔다. 그 모양이 곧 「끔」이다.
--      (덤프: %TEMP%\hitpan-taxinvoice-gate\fit-measurements.txt · 전 20행 모두 False)
--   ② 「켬」은 품목이 많을 때 마지막 칸을 「외 N건」으로 바꾼다. 세금계산서는 법정
--      문서라, **고객이 직접 고르지 않았는데** 품목 줄이 종이에서 빠지면 안 된다.
--      §10-2 도 *"고객이 스스로 고른 경우에만 그렇게 된다"* 라고 적고 있다.
--   ⇒ 둘 다 0 을 가리킨다. 켜고 싶은 고객은 양식정보설정에서 한 번 켜면 된다.
--
-- ⚠️ print_copy_mode(DB-90) 와 축이 다르다:
--     print_copy_mode = **누구 몫**을 찍나 (둘 다 / 거래처만 / 우리만)
--     show_tear_line  = 둘 다 찍을 때 **한 장에 모을까** (켬) **쪽을 나눌까** (끔)
--   그래서 print_copy_mode 가 both 가 아니면 이 칸은 아무 일도 하지 않는다.
--
-- 멱등: 컬럼 존재 여부를 확인한 뒤에만 추가한다 (DB-90 과 같은 꼴).
-- 🔴 출하 DDL(installer/hitpan_db_clean.sql) 에도 같은 칸을 넣었다 (#36).
-- =============================================================

SET @col_exists := (
  SELECT COUNT(*) FROM information_schema.columns
  WHERE table_schema = DATABASE()
    AND table_name = 'form_templates'
    AND column_name = 'show_tear_line'
);

SET @sql := IF(@col_exists = 0,
  'ALTER TABLE `form_templates`
     ADD COLUMN `show_tear_line` tinyint(1) NOT NULL DEFAULT 0
       COMMENT ''1=한 장에 두 벌+가운데 자르는 선 / 0=벌마다 한 쪽씩 (DB-147). print_copy_mode=both 일 때만 쓰인다''',
  'SELECT 1');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;
