-- ─────────────────────────────────────────────────────────────
-- 무엇이 막혀 있었나 — 칸이 하나뿐이라 두 가지를 못 담는다
-- ─────────────────────────────────────────────────────────────
--
--   현행: UNIQUE(tenant_id, fingerprint) + fingerprint NOT NULL.
--   기기를 알아보는 값을 담을 칸이 `fingerprint` **하나뿐**이다.
--
--   그런데 히트판에는 서로 다른 두 종류의 값이 들어온다:
--     · 메인PC   → MainPcRegistrationService 가 만드는 `MAINPC-…`
--                  (MachineName·회사코드·슬롯번호로 만든다 — 서버가 자기를 아는 값)
--     · 브라우저 → device-fingerprint.js 가 만드는 `HFPv2-…`
--                  (브라우저가 자기를 신고하는 값 — 브라우저마다 다르다)
--
--   같은 컴퓨터인데 두 값이 다르고, 담을 칸이 하나라서 **두 줄이 된다.**
--   ⇒ 한 대의 PC 가 슬롯 2개를 먹는다. 고객이 쓰지도 않은 자리에 돈을 낸다.
--     (P0 스냅샷 ②-2 증상 1 — 코드로 원인이 확정된 건이다)
--
--   🔴 칸을 나누지 않으면 **한 줄이 두 값을 동시에 가질 수 없다.**
--     명세서 §17-2 가 "메인PC 합류가 물리적으로 성립하지 않는다" 고 판정한 자리가 여기다.
--
-- ─────────────────────────────────────────────────────────────
-- 무엇을 하는가 — 칸을 나눈다. 지우지 않는다
-- ─────────────────────────────────────────────────────────────
--
--   ① `hardware_id`  신설 — 서버가 읽는 하드웨어 식별값(장비넘버). 메인PC 용.
--   ② `fingerprint`  격하 — **옛 기기 호환 전용**으로 남긴다.
--
--   🚨 헌법 #37 — `fingerprint` 를 **지우지 않는다.** "안 읽힌다 ≠ 잔재".
--     이미 등록된 고객 기기는 전부 이 값으로만 찾을 수 있다. 지우는 순간
--     쓰던 사람이 전부 새 기기가 되어 슬롯을 다시 먹는다.
--     ⇒ 컬럼도, NOT NULL 도, UNIQUE(uq_tenant_fp) 도 **그대로 둔다.**
--
--   ⚠️ 이 마이그레이션은 **칸만 만든다.** 그 칸을 읽고 쓰는 코드는 2차(P3 열쇠 교체)다.
--     "DB 는 미리 다, 코드는 필요할 때만"(헌법 #9) 이 그대로 적용되는 자리다.
--     지금 이 컬럼은 전 행이 NULL 이고 아무도 읽지 않는다 — 그래서 무회귀다.
--
-- ─────────────────────────────────────────────────────────────
-- UNIQUE 제약 재설계 — 한 줄이 장비넘버와 지문을 동시에 갖게
-- ─────────────────────────────────────────────────────────────
--
--   기존 uq_tenant_fp (tenant_id, fingerprint)      ← 그대로 살려 둔다
--   신설 uq_tenant_hardware (tenant_id, hardware_id) ← 새로 건다
--
--   🔴 두 UNIQUE 가 **각자 독립**이라 한 줄이 두 값을 동시에 가질 수 있다.
--     이것이 §17-2 가 요구한 바로 그 형태다.
--
--   ⚠️ 왜 hardware_id 는 NULL 을 허용하는가 — 이것이 이 설계의 핵심이다.
--     MariaDB(및 MySQL)의 UNIQUE 인덱스는 **NULL 을 서로 다른 값으로 본다.**
--     ⇒ hardware_id 가 NULL 인 행은 **몇 개든 공존한다.**
--     ⇒ 장비넘버를 아직 못 받은 **기존 고객 기기 전부가 그대로 산다.**
--       (실측 확인: NULL 2행 공존 OK / 같은 tenant 안 같은 값은 1062 로 차단 OK)
--
--     반대로 NOT NULL DEFAULT '' 로 만들었다면 빈 문자열이 서로 충돌해
--     **기존 고객의 두 번째 기기부터 INSERT 가 죽는다.** 그래서 NULL 허용이 유일한 답이다.
--
--   ⚠️ 왜 tenant_id 를 앞에 두는가 — 헌법 #2 격리.
--     장비넘버는 회사 안에서만 유일하면 된다. 전역 UNIQUE 로 걸면 다른 회사가
--     같은 장비넘버를 못 쓰게 되어, 남의 회사 사정이 우리 고객을 막는다.
--
-- ⚠️ 길이를 128 로 잡은 이유
--   fingerprint 는 varchar(64) 다(SHA-256 hex 64자에 맞춘 값).
--   장비넘버는 아직 무엇으로 만들지 확정되지 않았다(P0 미확인 U-4 · 명세서 §10-2 — P3·P4).
--   메인보드 UUID·디스크 일련번호 같은 원본값이 그대로 들어올 여지를 남긴다.
--   ⇒ 좁게 잡아 나중에 늘리는 것보다 넉넉히 잡아 두는 쪽이 안전하다.
--
-- 대상 DB: hitpan_erp (고객 PC 로컬 ERP DB)
--          신규 설치 단일 진실원 installer/hitpan_db_clean.sql 에 함께 편입한다(헌법 #36).
-- 헌법: #1 추가만 / #9 DB 는 미리 다 / #13 DESCRIBE 선행 / #17 InnoDB / #36 / #37 컬럼 제거 금지
--
-- 멱등: ADD COLUMN IF NOT EXISTS + ADD UNIQUE INDEX IF NOT EXISTS.
--       MariaDB 11.4 에서 재적용 무해함을 실측 확인했다.
--       ⚠️ CREATE INDEX 는 IF NOT EXISTS 를 지원하지 않는다(DB-86 주석 참조).
--          ALTER TABLE … ADD INDEX IF NOT EXISTS 형태여야 멱등이다.
-- =============================================================

-- ① 장비넘버 칸 신설 — 서버가 읽는 하드웨어 식별값
ALTER TABLE tenant_devices
    ADD COLUMN IF NOT EXISTS hardware_id VARCHAR(128) DEFAULT NULL
        COMMENT '장비넘버(하드웨어 식별값). 서버가 읽는 변하지 않는 값. NULL=아직 못 받은 옛 기기 (DB-103)';

-- ② 장비넘버는 회사 안에서 유일하다 — NULL 은 몇 개든 공존한다(옛 기기 보존)
ALTER TABLE tenant_devices
    ADD UNIQUE INDEX IF NOT EXISTS uq_tenant_hardware (tenant_id, hardware_id);

-- ③ `fingerprint` 격하 — 옛 기기 호환 전용임을 컬럼 설명에 남긴다
--   🚨 헌법 #37 — 지우지 않는다. 타입·NULL 여부·UNIQUE 전부 그대로다.
--     바뀌는 것은 **설명뿐**이다. 다음 사람이 이 칸을 "새 기기를 찾는 열쇠" 로
--     오해하고 코드를 짜는 것을 막는 것이 이 한 줄의 목적이다.
ALTER TABLE tenant_devices
    MODIFY COLUMN fingerprint VARCHAR(64) NOT NULL
        COMMENT '[옛 기기 호환 전용] 브라우저 환경해시(HFPv2-)·메인PC(MAINPC-). 새 기기는 hardware_id 로 잡는다 (DB-103 격하)';
