-- 무엇이 빠져 있었나
--
--   슬롯을 계정이 아니라 **등록 기기**로 세기로 처음부터 정했고, 메인PC(히트판 본체·DB 를
--   가진 그 PC)와 클라이언트를 구분하기로도 정해 두었다. 그런데 그 구분을 담을 자리가
--   테이블에 없었다. 설치마법사가 tenant_devices 에 넣는 코드도 0건이었다.
--   그러면서 코드 주석과 고객 화면은 "설치 과정에서 함께 등록됩니다" 라고 적고 있었다.
--   ⇒ 없는 것을 있다고 적어 둔 상태였다.
--
-- 왜 지금 필요한가 — CS 축 (사장님 지적)
--
--   고객이 "히트판이 안 돼요" 라고 전화하면 CS 는 먼저 물어야 한다 — 그 PC 가 메인PC 인가.
--     · 메인PC 면    → 본체·DB·터널이 그 PC 에 있다. 그 PC 를 살려야 한다
--     · 클라이언트면 → 본체는 멀쩡하고 메인PC 가 꺼졌을 수 있다. "사무실 그 컴퓨터 켜져 있나요?"
--   구분이 화면에 없으면 이 첫 질문을 못 던진다. 기능 누락이 아니라 운영 불능이다.
--
-- 왜 새 컬럼인가 — 다른 자리를 쓸 수 없는 이유
--
--   · device_type 에 'main' 추가 → ✋ TenantDeviceService 가 pc/mobile/tablet 외 값을 'pc' 로
--     강제 정규화하고 쿼터 집계가 이 3값 기준이라 **한도 계산이 즉시 깨진다**
--   · status 에 새 값 추가       → ✋ status='approved' 로 접근 통제를 한다. 오염 위험
--   · device_name 에 문자열 표식 → ✋ 고객이 기기 이름을 바꾸는 기능이 생기는 순간 깨진다.
--     쿼리로 "메인PC 1건" 을 제약할 수도 없다
--   ⇒ 독립 컬럼이 유일하게 안전하다.
--
-- ⚠️ 테넌트당 1건 제약을 DB 에 걸지 않는 이유
--   MariaDB 에는 부분 UNIQUE 인덱스가 없다. UNIQUE(tenant_id, is_main_pc) 를 걸면
--   is_main_pc=0 인 일반 기기가 테넌트당 1대만 허용되어 정반대 사고가 난다.
--   ⇒ 1건 보장은 애플리케이션(TenantDeviceService)에서 한다. 등록 직전에 이미 있는지 본다.
--
-- ⚠️ 기존 고객 데이터를 건드리지 않는다
--   기존 행은 전부 is_main_pc=0 으로 시작한다. 어느 기기가 메인PC 였는지 DB 만 보고
--   판정할 방법이 없기 때문이다(지문은 접속 주소와 무관하게 설계돼 있다).
--   ⇒ 메인PC 서버에서 다음 로그인이 일어날 때 그 기기가 메인PC 로 확정된다.
--     이미 일반 기기로 등록돼 있으면 그 행이 승격된다(새 행을 만들지 않는다 — 슬롯 이중소모 방지).
--
-- 대상 DB: hitpan_erp (고객 PC 로컬 ERP DB)
--          신규 설치 단일 진실원 installer/hitpan_db_clean.sql 에 함께 편입한다(헌법 #36).
-- 헌법: #1 추가만 / #9 DB 는 미리 다 / #36 clean DDL 편입 / #37 컬럼 제거 금지
--
-- 멱등: ADD COLUMN IF NOT EXISTS (MariaDB 10.0+). 재적용해도 안전하다.
-- =============================================================

ALTER TABLE tenant_devices
    ADD COLUMN IF NOT EXISTS is_main_pc TINYINT(1) NOT NULL DEFAULT 0
        COMMENT '메인PC(히트판 본체·DB 보유) 여부. 테넌트당 1대 — 보장은 애플리케이션에서 한다';

-- ⚠️ 인덱스를 따로 만들지 않는다.
--   MariaDB 는 CREATE INDEX 에 IF NOT EXISTS 를 지원하지 않아 재적용 시 1061 로 깨진다
--   (ADD COLUMN 은 지원한다 — 위 구문). 멱등이 깨지면 MigrationRunner 재실행에서 기동이 멈춘다.
--   그리고 필요하지도 않다 — 기존 idx_tenant_type_status 가 tenant_id 를 선두로 가지고 있어
--   테넌트로 좁히는 일은 이미 인덱스를 탄다. 그 뒤 남는 행은 기기 몇 대뿐이라 스캔이 무의미하다.
