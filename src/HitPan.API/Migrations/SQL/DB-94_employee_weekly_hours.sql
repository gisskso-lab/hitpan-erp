--
-- 🔴 왜 필요한가
--
--   사장님 지시(2026-08-12): "정직원이냐, 알바냐, 계약직이냐, 무기계약직이냐 에 따라서도 달라짐"
--
--   그런데 고용형태만으로는 판정이 안 되는 자리가 있다. 같은 '알바' 라도
--   주 20시간과 주 10시간은 법적 취급이 다르다(주 15시간이 갈림길).
--   연차·주휴수당·4대보험 가입 판정이 전부 이 숫자를 본다.
--
--   실측 결과 이 숫자를 담는 칸이 어디에도 없다:
--     · attendance.work_hours — 실제로 근무한 시간(실적)이지 약정이 아니다
--     · 전자근로계약서 work_hours — varchar 자유 텍스트("주 40시간" 같은 말). 계산 불가
--
--   ⇒ employees 에 숫자 칸을 연다.
--
-- 🔴 반자동 원칙(사장님 2026-08-12: "히트판은 100%자동화는 없어. 무조건 반자동이야")
--
--   NULL 을 허용한다. 기본값을 40 으로 채우지 않는다.
--   기존 12명이 정말 주 40시간인지 우리는 모른다 — 모르는 것을 아는 척 채우면
--   그 값으로 연차가 계산되고, 틀린 줄도 모른 채 법정 미달이 될 수 있다.
--   NULL = "아직 안 정했다" 이고, 화면이 그렇게 보여주고, 사람이 확정한다.
--
-- ⚠️ 값 자체는 법정값이 아니라 '회사와 직원의 약정' 이다. 그래서 설정 테이블이 아니라
--    사원마다 갖는 칸이 맞다. (법정값 — 주 15시간 기준 같은 것 — 은 설정 테이블로 간다)
--
-- 멱등: information_schema 확인 후 동적 ALTER. 두 번 돌려도 무해하다.
-- ═══════════════════════════════════════════════════════════════

SET @col_exists := (
    SELECT COUNT(*) FROM information_schema.columns
    WHERE table_schema = DATABASE()
      AND table_name = 'employees'
      AND column_name = 'weekly_hours'
);

SET @ddl := IF(@col_exists = 0,
    'ALTER TABLE employees
       ADD COLUMN weekly_hours decimal(4,1) DEFAULT NULL
       COMMENT ''주당 소정근로시간(약정). NULL=미정 — 반자동 원칙상 임의로 채우지 않는다''',
    'SELECT ''DB-94: employees.weekly_hours already exists'' AS skipped');

PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
