-- ─────────────────────────────────────────────────────────────
-- 무엇이 문제였나
-- ─────────────────────────────────────────────────────────────
--
--   메인PC 판정이 `터널 헤더 없음 AND 루프백` 하나뿐이었다(MainPcOnlyAttribute:38).
--   그런데 고객은 **도메인(터널)으로 접속한다.** Cloudflare 가 `CF-Connecting-IP` 를
--   반드시 붙이므로 **첫 조건에서 항상 탈락한다.**
--   ⇒ 도메인으로 여는 한 메인PC 로 인식된 적이 한 번도 없다(불안정이 아니라 100% 실패).
--   ⇒ 자료관리(백업·초기화·자료이관)가 전부 403.
--
--   IP 로는 영영 못 가린다 — cloudflared 가 **그 PC 안에서** 히트판을 다시 부르므로
--   서버가 보는 소켓 주소는 외부 접속이든 메인PC 든 **항상 127.0.0.1** 이다.
--   같은 사무실이면 공인 IP 도 같다(실측 124.194.59.154).
--
-- ─────────────────────────────────────────────────────────────
-- 이 칸이 무엇을 담나 — 「왕복 증명」의 비밀
-- ─────────────────────────────────────────────────────────────
--
--   브라우저가 자기 PC 안의 히트판(127.0.0.1)을 두드려 증표를 받아 온다.
--   받아 오면 메인PC, 못 받아 오면 클라이언트다.
--   그 증표를 만드는 비밀(HMAC 키)이 이 칸에 들어간다.
--
--   🔴 원문을 담지 않는다. **봉인된 상태**로만 담는다.
--     TpmKeyService.SealKey() — TPM 2.0 칩에 봉인(NCRYPT_PLATFORM_KEY_FLAG),
--     TPM 없는 PC 는 DPAPI(DataProtectionScope.LocalMachine) 폴백.
--     ⇒ **그 PC 에서만 풀린다.** DB 가 통째로 새어도, 이 값을 다른 PC 로 옮겨도
--       봉인이 안 풀리므로 남의 메인PC 가 될 수 없다(헌법 #5 계통).
--
-- ─────────────────────────────────────────────────────────────
-- 🔴 왜 파일이 아니라 DB 인가 — 이것이 이 설계의 급소다
-- ─────────────────────────────────────────────────────────────
--
--   사장님 결재: 메인PC 를 **되돌릴 수 있어야 한다**(새 컴퓨터로 이전).
--   그 판정은 *"봉인이 풀리는가"* 하나로 한다 — 안 풀리면 등록된 그 PC 가 아니다.
--
--   ⇒ 이 값이 **자료와 함께 이사해야** 판정이 성립한다.
--     새 PC 에서 백업을 복원하면 옛 PC 의 봉인키가 따라 들어오고,
--     그 값이 **안 풀리는 것**이 곧 "컴퓨터가 바뀌었다" 는 신호가 된다.
--     → [메인PC 변경] 팝업 → 새 키로 갱신.
--
--   🔴 파일(hitpan-keys.conf)에 두면 복원해도 안 따라오므로 **이 신호가 영영 안 뜬다.**
--     그러면 고객이 컴퓨터를 바꾸는 순간 메인PC 를 **영영 못 옮긴다.**
--     (설계문서 §3-5 ④ 가 이 전제 위에 서 있다)
--
--   ⚠️ 설치본에 키를 미리 심지 않는다 — 등록 시점에 만든다.
--     ⇒ 설치 프로그램·업데이트·워치독 흐름 **무접촉**(헌법 #43 Major 팝업 불변).
--     ⇒ 이미 깔린 고객도 **다음 로그인 팝업 한 번**으로 끝난다.
--
-- ─────────────────────────────────────────────────────────────
-- 왜 NULL 을 허용하나
-- ─────────────────────────────────────────────────────────────
--
--   기존 고객의 기기는 전부 이 값이 없다. NOT NULL 로 만들면 그 기기들이 막힌다.
--   NULL = "아직 메인PC 로 등록되지 않았거나, 옛 방식으로 등록된 기기" 다.
--   메인PC 등록 팝업을 누르는 순간 채워진다.
--   ⚠️ **규칙을 켜서 쓰던 사람이 막히는 일은 만들지 않는다**(2026-08-10 4차 사고 계통).
--
-- ─────────────────────────────────────────────────────────────
-- 왜 VARBINARY 인가 / 왜 1024 인가
-- ─────────────────────────────────────────────────────────────
--
--   ProtectedData.Protect / NCrypt 출력은 **바이너리**다. base64 로 바꿔 담으면
--   인코딩 왕복이 한 겹 늘고, 콜레이션이 끼어들 여지가 생긴다(#13 계통 사고).
--   ⇒ 나온 그대로 담는다.
--
--   길이: 32바이트 키의 DPAPI 출력이 대략 300바이트 안팎, TPM 봉인은 그보다 크다.
--   좁게 잡아 나중에 늘리는 것보다 넉넉히 잡아 두는 쪽이 안전하다(DB-103 과 같은 판단).
--
-- ─────────────────────────────────────────────────────────────
-- 🚫 건드리지 않는 것
-- ─────────────────────────────────────────────────────────────
--
--   · `is_main_pc` · `main_pc_key`(GENERATED) · `uq_tenant_main_pc` — DB-120 의 1대 보장 장치.
--     그대로 둔다. 이 칸은 그 위에 얹히기만 한다.
--   · `fingerprint` · `uq_tenant_fp` — 헌법 #37. 옛 기기 전부가 이 값으로만 찾힌다.
--   · `hardware_id` — 이 작업은 이 칸을 **쓰지 않는다**(기기 식별은 별건).
--   · `auth_key_hash` — 기기 승인용. 메인PC 봉인키와 층이 다르다.
--
-- 대상 DB: hitpan_erp (고객 PC 로컬 ERP DB)
--          신규 설치 단일 진실원 installer/hitpan_db_clean.sql 에 함께 편입한다(헌법 #36).
-- 헌법: #1 추가만 / #5 암호화 / #9 DB 는 미리 다 / #13 DESCRIBE 선행 / #36 clean DDL 편입
--       #37 컬럼 제거 금지 / #43 워치독 무접촉
--
-- 멱등: ADD COLUMN IF NOT EXISTS (MariaDB 10.0+). 재적용해도 안전하다.
--       ⚠️ CREATE INDEX 는 IF NOT EXISTS 를 지원하지 않는다 — 인덱스를 만들지 않는다(아래 사유).
-- =============================================================

-- ① 봉인된 메인PC 인증키
ALTER TABLE tenant_devices
    ADD COLUMN IF NOT EXISTS mainpc_sealed_key VARBINARY(1024) DEFAULT NULL
        COMMENT '메인PC 인증키 — TPM/DPAPI 로 그 PC 에 봉인된 상태. 원문 미저장. NULL=미등록 (DB-126)';

-- ② 언제부터 이 컴퓨터가 메인PC 였나 — 변경 이력을 사람이 읽을 수 있게
ALTER TABLE tenant_devices
    ADD COLUMN IF NOT EXISTS mainpc_key_issued_at DATETIME(6) DEFAULT NULL
        COMMENT '메인PC 인증키 발급(= 메인PC 등록·변경) 시각 (DB-126)';

-- ⚠️ 인덱스를 만들지 않는다.
--   이 칸으로 행을 **찾지 않는다.** 언제나 `is_main_pc = 1` 로 먼저 좁힌 뒤(그 줄은 회사당 1개,
--   uq_tenant_main_pc 가 보장한다) 그 줄의 값을 읽을 뿐이다.
--   봉인값에 인덱스를 거는 것은 이득이 없고, MariaDB 는 CREATE INDEX 에 IF NOT EXISTS 를
--   지원하지 않아 재적용 시 1061 로 멱등이 깨진다(DB-86 주석 참조).
