-- ─────────────────────────────────────────────────────────────
-- 왜 DB-127 을 고치는 것만으로는 안 되나 — 급소다
-- ─────────────────────────────────────────────────────────────
--
--   DB-127:114 는 `ADD COLUMN IF NOT EXISTS ... DEFAULT 1` 이다.
--   그 줄의 `DEFAULT` 를 0 으로 고쳐도 **이미 DB-127 을 적용한 DB 는 한 줄도 안 바뀐다.**
--   컬럼이 이미 있으니 `IF NOT EXISTS` 가 그 문장을 통째로 건너뛰기 때문이다.
--   그래서 이 파일이 두 가지를 같이 한다:
--
--       ① MODIFY  — 앞으로 들어올 **새 행**의 기본값을 0 으로
--       ② UPDATE  — 이미 1 로 들어와 있는 **기존 행**을 0 으로
--
--   ①만 하면 기존 테넌트는 계속 1(켜짐)로 남는다. ②만 하면 다음에 생기는
--   테넌트가 다시 1 로 켜진다. **둘 다 해야 양쪽이 닫힌다.**
--   ⇒ 게이트 G-B8 의 음성 대조군이 바로 이것이다: `UPDATE` 를 지우면 값이 1 로 남아 FAIL.
--
-- ─────────────────────────────────────────────────────────────
-- 🔴 왜 기본 OFF 로 출하하나 — 켜서 출하하면 고객이 튕긴다
-- ─────────────────────────────────────────────────────────────
--
--   축 B(같은 계정 PC 동시로그인 차단)는 **한 번도 실제로 걸려본 적이 없는 판정**이다
--   (user_sessions INSERT 가 레포 전체에 0건이었다 — DB-127 머리말).
--   넣는 코드가 이번에 살아나는 순간 판정식이 처음으로 참이 될 수 있다.
--   그 상태로 기본값 1 을 내보내면, 배포 당일 두 대에서 쓰던 고객이 로그인을 못 한다.
--
--   ⇒ **살리되 꺼둔다.** 켜는 날은 선례 수준 도달을 확인한 뒤 별도 결재로 온다
--     (전결 §6 · 작지 §3 금지 3c — *"`enforce_single_pc_login` 을 켜지 마라"*).
--   ⚠️ 다음 사람에게: 이 파일이 0 으로 내렸다는 사실만 읽고 *"차단이 없다"* 로 오해하지 마라.
--     차단 코드는 살아 있다. 스위치만 내려둔 것이고, 스위치는 **배포 없이** DB 에서 켠다.
--
-- ─────────────────────────────────────────────────────────────
-- 🚫 건드리지 않는 것
-- ─────────────────────────────────────────────────────────────
--
--   · `user_sessions.device_kind` 기본값 `'mobile'` — 8/16 CR2-2 최종 판정이다.
--     `'pc'` 로 되돌리면 고객이 쓰지도 않은 비싼 칸에 돈을 낸다 = P0
--     (DB-127:88-93 · 작지 §3 금지 3)
--   · `enforce_tenant_session_limit`(축 A) — 이미 DEFAULT 0 이다. 다른 축이라 손대지 않는다
--   · 컬럼 삭제·이름변경 없음 (헌법 #1 추가만 · #37)
--   · 새 테이블 없음 ⇒ ENGINE 지정 대상도 없다 (#17 해당 없음)
--
-- 대상 DB: hitpan_erp (고객 PC 로컬 ERP DB)
--          신규 설치 단일 진실원 installer/hitpan_db_clean.sql 에 함께 편입한다(헌법 #36).
--          🔴 clean DDL 의 `schema_migrations` 시드에 ('DB-128','clean-ddl',1) 도 같이 넣었다.
--             빠뜨리면 신규설치 고객이 이 마이그를 영원히 건너뛴다(DB-89·DB-126 선례).
-- 헌법: #1 추가만 / #13 DESCRIBE 선행(2026-09-27 실측 — 아래) / #36 clean DDL 편입 / #37
--
-- #13 DESCRIBE 실측 (2026-09-27 · information_schema.COLUMNS):
--   hitpan_e2e.tenant_settings.enforce_single_pc_login       tinyint(1)  COLUMN_DEFAULT = 1
--   hitpan_e2e.tenant_settings.enforce_tenant_session_limit  tinyint(1)  COLUMN_DEFAULT = 0
--   ⇒ 축 B 만 1(켜짐)이다. 이 파일이 그 하나를 0 으로 내린다.
--
-- 멱등: MODIFY 는 같은 정의로 다시 돌려도 안전하고, UPDATE 는 이미 0 인 행을 건드리지 않는다.
--       재적용해도 결과가 같다.
