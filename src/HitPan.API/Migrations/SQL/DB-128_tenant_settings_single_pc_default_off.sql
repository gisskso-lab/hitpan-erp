-- ① 앞으로 들어올 새 행의 기본값 — 1(켬) → 0(끔)
ALTER TABLE tenant_settings
    MODIFY COLUMN enforce_single_pc_login TINYINT(1) NOT NULL DEFAULT 0
        COMMENT '축B 같은 계정 PC 동시로그인 차단 사용 여부. 0=끔(기본 · DB-128). 켜는 것은 별도 결재. 모바일은 대상 아님 (DB-127 신설 · DB-128 기본 OFF)';

-- ② 이미 1 로 들어와 있는 기존 행 — 0 으로 내린다
--   🔴 이 문장이 없으면 ①은 기존 DB 에서 아무 일도 안 한다. G-B8 음성 대조군.
--   WHERE 로 좁힌 이유: 이미 0 인 행은 건드리지 않아 감사 흔적이 덜 흔들린다.
UPDATE tenant_settings
   SET enforce_single_pc_login = 0
 WHERE enforce_single_pc_login <> 0;
