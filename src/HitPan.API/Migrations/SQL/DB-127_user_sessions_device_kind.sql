-- ─────────────────────────────────────────────────────────────
-- 무엇이 문제였나
-- ─────────────────────────────────────────────────────────────
--
--   동시접속 제한이 **한 번도 걸린 적이 없다.**
--   세는 코드(SessionLimitMiddleware:114)도 지우는 코드(AuthController:336)도 있는데
--   **넣는 코드가 레포 전체에 0건**이라 user_sessions 가 항상 비어 있었다.
--   ⇒ 판정식 `activeCount > limit` 의 왼쪽이 영원히 0 이다.
--
--   9/25 결재로 과금 축이 **기기 슬롯 → 계정**으로 바뀌었다.
--   「계정 5개 = PC 5대」를 강제하려면 **PC 세션만** 세야 한다.
--   모바일은 FREE 이므로 세면 안 된다.
--
-- ─────────────────────────────────────────────────────────────
-- 🔴 왜 user_agent 를 안 쓰고 칸을 새로 만드나 — 급소다
-- ─────────────────────────────────────────────────────────────
--
--   user_sessions 에는 이미 `user_agent VARCHAR(500)` 이 있다. 그것으로 모바일을
--   가르고 싶어지지만, **하면 안 된다.**
--
--   ① UA 는 **사용자가 바꿀 수 있다.** 모바일이 FREE 이므로
--      UA 만 모바일로 바꾸면 **PC 에서 무제한 접속이 된다.** 과금이 그대로 뚫린다.
--   ② UA 규칙은 브라우저 개편마다 깨진다 ⇒ 조용히 오판정한다.
--   ③ 메인PC 트랙(9/22~25)에서 이미 겪었다 —
--      **브라우저가 말해주는 것 위에 정책을 세우면 안 된다.**
--
--   ⇒ 서버가 판정해 적는 칸을 따로 둔다. UA 는 **사람이 읽는 기록**으로만 남긴다.
--
-- ─────────────────────────────────────────────────────────────
-- 🔴 왜 기본값이 'mobile' 인가 — 초안을 뒤집었다
-- ─────────────────────────────────────────────────────────────
--
--   이 파일 초안은 *"모르면 과금되는 쪽('pc')으로"* 라고 적었다. **틀렸다.**
--   히트판에는 이미 판정이 끝난 원칙이 있다:
--
--       **"모르는 것은 싼 칸으로"** — 모르는 값 → mobile
--       (20260815 아키텍처명세서 §3 #4 — *"ERP 가 맞다"* 로 판정 완료.
--        백오피스가 ERP 규칙에 맞춰졌다: DeviceRegistrationController.cs:89-96)
--
--   근거가 된 실제 사고: 백오피스가 모르는 값을 'pc' 로 보내
--   **고객이 쓰지도 않은 비싼 자리에 돈을 냈다.** `?? "pc"` 폴백도 같은 이유로 걷어냈다
--   (20260815작3 P1 I-6 · AuthController.cs:99-111).
--
--   ⇒ 같은 규칙을 여기에도 쓴다. 규칙을 **두 개 만들지 않는다.**
--     차단 축에서도 mobile 은 「안 막힘」 = 고객에게 유리한 쪽이라 방향이 같다.
--
--   ⚠️ **남는 구멍을 숨기지 않는다** — DeviceType 을 안 보내는 클라이언트는
--     mobile 로 떨어져 **축 B 차단을 안 받는다.**
--     받아들이는 이유: ① 위 원칙이 이미 그렇게 판정됐다
--     ② ERP 웹은 항상 보낸다(Web/Services/AuthService.cs:45 `hitpanDevice.getDeviceType`)
--     ③ 과금 축이 **계정**으로 바뀌어(9/25 결재) 이 구멍이 매출로 이어지지 않는다.
--     ⇒ 매출 누수가 아니라 **차단 누락**이다. 그 값은 게이트 G-3 가 지킨다.
--
-- ─────────────────────────────────────────────────────────────
-- 왜 VARCHAR 가 아니라 ENUM 인가
-- ─────────────────────────────────────────────────────────────
--
--   값이 2개로 닫혀 있고, 늘어날 계획이 없다. ENUM 이면 **DB 가 오타를 거절한다.**
--   VARCHAR 로 두면 'PC'·'Pc'·'mobile ' 이 섞여 들어와도 통과하고,
--   그 순간 `device_kind = 'pc'` 판정이 조용히 빗나간다(콜레이션 사고 계통).
--
-- ─────────────────────────────────────────────────────────────
-- 🚫 건드리지 않는 것
-- ─────────────────────────────────────────────────────────────
--
--   · `session_id`·`user_id`·`tenant_id` — 기존 키 구조 그대로
--   · `expires_at` — DB-28 이 넣은 칸. SessionLimitMiddleware 가 본다
--   · `is_active` — 옛 칸. 안 읽힌다고 지우지 않는다 (헌법 #37)
--   · `user_agent` — 기록용으로 그대로 둔다
--   · SessionLimitMiddleware — 축이 다르다. 한 줄도 안 건드린다
--
-- 대상 DB: hitpan_erp (고객 PC 로컬 ERP DB)
--          신규 설치 단일 진실원 installer/hitpan_db_clean.sql 에 함께 편입한다(헌법 #36).
-- 헌법: #1 추가만 / #9 DB 는 미리 다 / #13 DESCRIBE 선행(2026-09-27 실측) / #17 InnoDB
--       #36 clean DDL 편입 / #37 컬럼 제거 금지
--
-- 멱등: ADD COLUMN IF NOT EXISTS (MariaDB 10.0+). 재적용해도 안전하다.
-- =============================================================

-- ① 기기 종류 — 서버가 판정해 적는다. UA 추론 금지(위 사유).
--   판정 규칙은 새로 만들지 않는다: 'pc' 만 pc, 그 밖(빈값·tablet·모르는 값)은 전부 mobile.
--   (DeviceRegistrationController.cs:89-96 과 **같은 규칙** — 규칙만 같게, 코드는 각자)
ALTER TABLE user_sessions
    ADD COLUMN IF NOT EXISTS device_kind ENUM('pc','mobile') NOT NULL DEFAULT 'mobile'
        COMMENT '세션을 만든 기기 종류. pc=축B 동시로그인 차단 대상, mobile=대상 아님(FREE). 서버 판정값(UA 추론 아님). 기본 mobile=모르는 것은 싼 칸으로 (DB-127)';

-- ② 킬스위치 2개 (tenant_settings)
--
--   🔴 왜 appsettings 가 아니라 DB 인가
--     `appsettings.json` 은 헌법 #21 로 손댈 수 없다(WASM 부트 필수).
--     그리고 고객 화면에서 사고가 나면 **배포 없이** 꺼야 한다 —
--     게시 1회가 372MB·수십 분이다. 배포로만 끌 수 있는 스위치는 스위치가 아니다.
--
--   🔴 왜 축 A 는 기본 OFF 인가 — 이것이 이번 작업 최대 위험이다
--     세션을 넣기 시작하는 순간, **한 번도 돈 적 없는** 테넌트 총량 제한이
--     소리 없이 켜진다(넣는 코드가 없어 판정식 왼쪽이 늘 0 이었다).
--     한도를 넘는 고객은 그날부터 429 다.
--     ⇒ 꺼둔 채 출하한다. 켜는 날 테넌트별 활성 사용자 수를 먼저 잰다.
--     ⚠️ **「살리되 꺼둔다」** — 다음 사람이 「살린다」만 읽고 켜져 있다고 믿으면
--       이번 트랙을 만든 바로 그 사고를 되풀이한다.
ALTER TABLE tenant_settings
    ADD COLUMN IF NOT EXISTS enforce_tenant_session_limit TINYINT(1) NOT NULL DEFAULT 0
        COMMENT '축A 테넌트 총량 동시세션 제한(SessionLimitMiddleware) 사용 여부. 0=끔(기본). 켜기 전 테넌트별 활성 사용자 수 실측 필수 (DB-127)';

ALTER TABLE tenant_settings
    ADD COLUMN IF NOT EXISTS enforce_single_pc_login TINYINT(1) NOT NULL DEFAULT 1
        COMMENT '축B 같은 계정 PC 동시로그인 차단 사용 여부. 1=켬(기본). 모바일은 대상 아님 (DB-127)';

-- ③ 조회 경로 전용 인덱스
--   축 B 판정은 `user_id = ? AND device_kind = 'pc' AND expires_at > NOW()` 로 돈다.
--   idx_user(user_id) 만으로는 한 사용자의 모든 세션을 훑은 뒤 걸러야 한다.
--   ⚠️ MariaDB 는 CREATE INDEX 에 IF NOT EXISTS 를 지원하지 않아 재적용 시 1061 로
--     멱등이 깨진다(DB-126 주석). ⇒ ALTER TABLE ... ADD INDEX IF NOT EXISTS 로 만든다.
ALTER TABLE user_sessions
    ADD INDEX IF NOT EXISTS idx_user_kind_exp (user_id, device_kind, expires_at);
