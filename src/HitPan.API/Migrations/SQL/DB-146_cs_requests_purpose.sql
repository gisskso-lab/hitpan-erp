-- =============================================================
-- DB-146: cs_requests.purpose 신설 — 「본사가 보낸 안내의 종류」를 적는 칸 (20261014작3 T-1)
-- =============================================================
-- 근거: 작업지시서 20261014작3 §1 T-1 · 설계 20261014_설계_작3 §1 · 선행검증서 20261014_1V_작3 P-11
--
-- 왜 칸이 필요한가 (사장님 결재 결-D = ⓑ)
--   본사는 공지를 네 종류로 보낸다(업데이트공지사항·히트판 공지사항·프로모션 안내·기타 공지사항).
--   지금 ERP 는 그 종류를 **본문 머리 한 줄**(`[업데이트공지사항] 제목`)로만 들고 있다.
--   그래서 「업데이트 공지만 모아 보기」를 하려면 **본문 글자를 되읽어야** 한다.
--
--   사장님이 그 방식(ⓐ)을 버리고 **ⓑ 칸 신설**을 고르셨다. 이유가 정확하다 —
--   낱말은 사람이 정하는 것이어서 바뀐다(실제로 20261014작2 가 낱말 6종을 고쳤다).
--   본문 글자로 거르면 **낱말을 바꾸는 순간 필터가 조용히 깨진다.**
--   값으로 거르면 낱말을 몇 번 바꿔도 필터는 그대로다.
--
-- 왜 기존 칸으로 흉내내지 않나
--   `category` 는 **고객이 고른 문의 유형**(7모양 콤보)이다. 본사 안내는 유형이 아니다 —
--   섞으면 CS 분류 통계가 오염된다(DB-144 가 같은 이유로 origin 을 따로 세웠다).
--
-- 🔴 왜 DEFAULT NULL 인가 — 둘 다 사고다
--   ⓐ `DEFAULT 'etc'` 로 채우면 **이미 내려온 옛 쪽지가 「기타 공지사항이었다」고 말한다.**
--      우리는 그 쪽지의 종류를 **모른다**(작3 전에는 칸이 없었으니 기록이 없다).
--      모르는 것을 안다고 적는 것은 거짓이다.
--   ⓑ `NOT NULL` 로 두면 이 칸을 모르는 **기존 INSERT 들이 깨진다**
--      (게이트 하네스가 칸을 명시 열거한다 — ErpCsOriginQueryGateTests.InsertAsync).
--   ⇒ 비워 둔다. **화면에서는 「기타 공지사항」으로 보여 준다**(사장님 결-D: 옛 쪽지는 기타로 보인다).
--      저장은 「모른다」, 표시는 「기타」 — 두 사실을 데이터에서 구분해 둔다.
--
-- 기존 행에 미치는 영향 — 0
--   `UPDATE` 문이 **이 파일에 한 줄도 없다.** 이미 있는 쪽지는 한 칸도 안 바뀐다(#1).
--   고객이 쓴 문의(`origin='local'`)는 늘 NULL 이다 — 그쪽에는 종류가 없다.
--
-- 🔴 추가형 마이그 — 재실행 안전(IF NOT EXISTS). ERP 는 MariaDB 다.
--    (백오피스는 MySQL 8 이고 거기서는 이 문법이 1064 다 — 10/11 사고. 이 파일은 ERP 축이다.)
-- =============================================================

ALTER TABLE cs_requests
    ADD COLUMN IF NOT EXISTS purpose varchar(20) DEFAULT NULL
        COMMENT '본사 발신 종류(update/notice/promo/etc/event/billing) — NULL = 작3 이전에 내려온 옛 쪽지(종류를 모른다) · 고객 문의(origin=local)는 늘 NULL (DB-146 · 작3 T-1)';

-- 공지 화면이 「이 종류만 보기」를 할 때 타는 길.
-- 🔴 `origin` 을 선행 칸으로 둔다 — 필터는 **항상 공지 쪽(origin='hq')에서만** 걸린다.
ALTER TABLE cs_requests
    ADD KEY IF NOT EXISTS idx_cs_req_purpose (tenant_id, origin, purpose, created_at);
