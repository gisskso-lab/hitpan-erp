-- =============================================================
-- DB-144: cs_requests.origin 신설 — 「본사가 먼저 보낸 쪽지」를 구별하는 칸 (작3 B-1)
-- =============================================================
-- 근거: 작업지시서 20261012작3 §2 D-2 · 선행검증서 20261012_1V 작3 §3
--
-- 왜 칸이 필요한가
--   10/11 작2 가 백오피스에 **본사 선발신 쪽지 큐**(bo_cs_outbound)를 세웠다 —
--   프로모션·이벤트·구독요금 미결재 안내를 **본사가 먼저** 고객사에 보내는 기능이다.
--   그 쪽지가 ERP 에 내려와 앉을 자리는 cs_requests 다(목록·쪽지함이 둘 다 이 표 기준 —
--   CsRequestController.cs:178 · CsInboxPage.razor:133). 새 표를 만들면 화면 둘을
--   새로 짜야 하고 흐름이 끊긴다(#20).
--
--   그런데 cs_requests 에는 **출처를 가릴 칸이 없다**(DB-139:23-38 전수 확인).
--   칸이 없으면 고객이 **「내가 쓰지 않은 쪽지」를 자기 문의와 구별하지 못한다** —
--   「이 화면, 처음 보는 사람이 혼자 쓸 수 있냐」 기준에 걸린다.
--
-- 왜 기존 값으로 흉내내지 않나
--   category='etc' 같은 기존 분류로 섞으면 **CS 분류 통계가 오염**된다(8종 정본은
--   고객이 고른 유형이다 — 본사 안내는 유형이 아니다).
--
-- 기존 행에 미치는 영향 — 0
--   DEFAULT 'local' 이라 이미 있는 쪽지는 **한 줄도 안 바뀐다**(#1).
--   읽는 코드도 'local' 을 종전과 같이 다룬다.
--
-- 🔴 추가형 마이그 — 재실행 안전(IF NOT EXISTS). ERP 는 MariaDB 다(백오피스 MySQL 8 과 판이 다르다).
--    이 파일은 ERP 축이라 MariaDB 문법을 그대로 쓴다.
-- =============================================================

ALTER TABLE cs_requests
    ADD COLUMN IF NOT EXISTS origin varchar(10) NOT NULL DEFAULT 'local'
        COMMENT 'local = 고객(자식계정)이 쓴 문의 · hq = 본사가 먼저 보낸 안내(작3 B-1)';

-- 목록이 「본사 안내」만 따로 세거나 거를 때 인덱스를 탄다.
ALTER TABLE cs_requests
    ADD KEY IF NOT EXISTS idx_cs_req_origin (tenant_id, origin, created_at);
