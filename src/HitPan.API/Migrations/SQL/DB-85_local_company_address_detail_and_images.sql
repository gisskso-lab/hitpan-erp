--       작업지시서: docs/운영기록/20260809작4_계정관리_전수결함_수정범위_작업지시서.md (⑤번)
--
-- 무엇이 문제였나
--
-- ① 상세주소가 저장 후 사라진다
--    저장(Application/Services/SettingsService.cs:298)은 기본주소와 상세주소를
--    공백 하나로 이어 붙여 local_company.address 단일 컬럼에 넣는다.
--    그런데 조회 SQL(:372-389)은 address 만 SELECT 하고 AddressDetail 은 아예 없다.
--    ⇒ 새로고침하면 주소칸에 "…테헤란로 123 5층 501호" 가 통째로 들어가고 상세주소칸은 빈칸.
--      거기서 상세주소를 다시 입력해 저장하면 "…123 5층 501호 5층 501호" 로 중복 누적되고,
--      200자를 넘으면 잘린다(:299-302). 저장할 때마다 주소가 길어졌다.
--    ⇒ 우편번호 API 자체는 정상이었다(CDN HTTP 200 · CSP 허용 · openDaumPostcode 존재 실측).
--      끊긴 자리는 "선택"이 아니라 "되돌아오기"였다.
--
-- ② 인장·헤더를 저장할 컬럼이 없다
--    화면은 로고·인장·헤더 3종을 등록받고 "등록되었습니다" 를 띄우는데,
--    local_company 에는 logo_url 하나뿐이라 인장·헤더는 저장할 자리 자체가 없었다.
--    (로고는 컬럼·서비스·API 가 이미 다 있었고 프론트가 안 쓰고 있었을 뿐이다.)
--    인장은 거래명세서·견적서에 찍혀야 하는 것이라 ERP 에서 빠질 수 없다.
--
-- 왜 varchar(200) 인가 (logo_url 과 동일 폭)
--   이미지 자체(base64)를 DB 에 넣지 않는다. 파일 경로·URL 만 담는다.
--   base64 를 컬럼에 넣으면 회사 정보 한 행이 수 MB 가 되어 조회마다 그 무게를 지불하게 된다.
--   실제 파일은 로컬 파일시스템에 두고 경로만 참조한다(고객 PC 로컬 구조, 헌법 #30).
--
-- 대상 DB: hitpan_erp (고객 PC 로컬 ERP DB)
--          신규 고객 PC 설치 단일 진실원 installer/hitpan_db_clean.sql 에 함께 편입한다(헌법 #36).
-- 헌법: #1 추가만(기존 컬럼 손대지 않음) / #9 DB 는 미리 다 / #17 InnoDB(기존 테이블 유지) /
--       #36 clean DDL 편입 / #37 컬럼 제거 금지 — address 는 그대로 둔다
--
-- 멱등: ADD COLUMN IF NOT EXISTS (MariaDB 10.0+). 재적용해도 안전하다.
--
-- ⚠️ 기존 데이터 이관을 하지 않는 이유
--    address 에 이미 합쳐져 저장된 값을 기계적으로 되쪼갤 안전한 규칙이 없다.
--    "서울시 강남구 테헤란로 123 5층 501호" 에서 어디까지가 기본주소인지 판정할 수 없고,
--    잘못 쪼개면 주소가 틀어진다(헌법 #25 안전하게).
--    ⇒ 기존 값은 address 에 그대로 두고, address_detail 은 NULL 로 시작한다.
--      고객이 다음에 주소를 저장할 때부터 정상 분리된다. 데이터 손실 0.
-- =============================================================

ALTER TABLE local_company
    ADD COLUMN IF NOT EXISTS address_detail VARCHAR(200) NULL DEFAULT NULL
        COMMENT '상세주소(동·호수 등). 기본주소(address)와 분리 저장 — 종전 합쳐 저장해 중복 누적되던 것 봉합',
    ADD COLUMN IF NOT EXISTS seal_url VARCHAR(200) NULL DEFAULT NULL
        COMMENT '인장 이미지 경로. 거래명세서·견적서 출력에 사용. base64 아님 — 경로만 저장',
    ADD COLUMN IF NOT EXISTS header_url VARCHAR(200) NULL DEFAULT NULL
        COMMENT '출력 헤더 이미지 경로. 문서 상단 머리글용. base64 아님 — 경로만 저장';
